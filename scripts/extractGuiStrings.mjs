import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const headerPath = path.join(root, 'VP500Gui_resources.h')
const sourcePath = path.join(root, 'VP500Gui_resources.c')
const outPath = path.join(root, 'src', 'process', 'guiStrings.de.ts')

function decodeCString(body) {
  let out = ''
  for (let i = 0; i < body.length; i += 1) {
    const char = body[i]
    if (char !== '\\') {
      out += char
      continue
    }
    const next = body[++i]
    if (next === 'n') out += '\n'
    else if (next === 'r') out += '\r'
    else if (next === 't') out += '\t'
    else if (next === 'x') {
      out += String.fromCharCode(parseInt(body.slice(i + 1, i + 3), 16))
      i += 2
    } else if (next >= '0' && next <= '7') {
      const octal = body.slice(i, i + 3).match(/^[0-7]{1,3}/)[0]
      out += String.fromCharCode(parseInt(octal, 8))
      i += octal.length - 1
    } else out += next
  }
  return out
}

function decodeBytes(body) {
  const bytes = [...body.matchAll(/0x([0-9a-fA-F]+)/g)].map((match) => parseInt(match[1], 16))
  while (bytes.length > 0 && bytes[bytes.length - 1] === 0) bytes.pop()
  return Buffer.from(bytes).toString('utf8')
}

const header = fs.readFileSync(headerPath, 'utf8')
const ids = new Map()
for (const match of header.matchAll(/^#define GX_STRING_ID_(\w+)\s+(\d+)/gm)) {
  ids.set(match[1], Number(match[2]))
}

const texts = new Map()
const source = fs.readFileSync(sourcePath, 'utf8')
for (const line of source.split(/\r?\n/)) {
  const match = line.match(/^GX_CONST GX_UBYTE disp_1_(\w+)_German\[\] = (.+);$/)
  if (!match) continue
  const rhs = match[2]
  if (rhs.startsWith('"') && rhs.endsWith('"')) texts.set(match[1], decodeCString(rhs.slice(1, -1)))
  else if (rhs.startsWith('{')) texts.set(match[1], decodeBytes(rhs))
}

const byId = new Map()
const missing = []
for (const [name, id] of ids) {
  if (!texts.has(name)) {
    missing.push(name)
    continue
  }
  byId.set(id, { name, text: texts.get(name) })
}

const entries = [...byId.entries()].sort((a, b) => a[0] - b[0])
const textLines = entries.map(([id, entry]) => `  ${id}: ${JSON.stringify(entry.text)},`)
const nameLines = entries.map(([id, entry]) => `  ${id}: ${JSON.stringify(entry.name)},`)

const file = `/* Generated by scripts/extractGuiStrings.mjs from VP500Gui_resources.h and VP500Gui_resources.c. */
export const GUI_STRING_DE: Record<number, string> = {
${textLines.join('\n')}
}

export const GUI_STRING_NAME: Record<number, string> = {
${nameLines.join('\n')}
}
`

fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, file)

const checks = [
  [126, 'Heizrate 1'],
  [640, 'Zieltemperatur'],
  [115, 'Ja'],
  [116, 'Nein'],
]
for (const [id, expected] of checks) {
  const actual = byId.get(id)?.text
  if (actual !== expected) {
    throw new Error(`String ${id} ist "${actual}", erwartet "${expected}"`)
  }
}
if (!byId.get(151)?.text.includes('C')) {
  throw new Error('Einheit 151 enthaelt kein Grad C')
}

console.log(
  `GUI-Strings: ${entries.length} IDs, ${missing.length} ohne deutschen Text, geschrieben nach ${path.relative(root, outPath)}`,
)
